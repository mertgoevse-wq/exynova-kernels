#!/usr/bin/env python3
"""Compile and validate GLSL compute shaders into C++17 SPIR-V header."""

from __future__ import annotations

import os
import struct
import subprocess
import sys
import tempfile
from pathlib import Path

SHADER_TOOLS_DIR = Path(
    r"C:\Users\Win11 Pro\Android\Sdk\ndk\27.2.12479018\shader-tools\windows-x86_64"
)
GLSLC = SHADER_TOOLS_DIR / "glslc.exe"
SPIRV_VAL = SHADER_TOOLS_DIR / "spirv-val.exe"


def compile_shader(comp_path: Path, spv_path: Path) -> list[int]:
    cmd_compile = [
        str(GLSLC),
        "--target-env=vulkan1.1",
        "-O",
        str(comp_path),
        "-o",
        str(spv_path),
    ]
    res = subprocess.run(cmd_compile, capture_output=True, text=True)
    if res.returncode != 0:
        raise RuntimeError(
            f"glslc failed for {comp_path.name}:\n{res.stdout}\n{res.stderr}"
        )

    cmd_val = [str(SPIRV_VAL), "--target-env", "vulkan1.1", str(spv_path)]
    val_res = subprocess.run(cmd_val, capture_output=True, text=True)
    if val_res.returncode != 0:
        raise RuntimeError(
            f"spirv-val failed for {comp_path.name}:\n{val_res.stdout}\n{val_res.stderr}"
        )

    raw = spv_path.read_bytes()
    if len(raw) % 4 != 0:
        raise RuntimeError(f"SPIR-V binary {spv_path} size ({len(raw)}) not a multiple of 4")
    return list(struct.unpack(f"<{len(raw) // 4}I", raw))


def format_array(name: str, words: list[int]) -> str:
    lines = [f"inline constexpr uint32_t kShader_{name}[] = {{"]
    for i in range(0, len(words), 8):
        chunk = words[i : i + 8]
        suffix = "," if i + 8 < len(words) else ""
        lines.append("    " + ", ".join(f"0x{w:08X}u" for w in chunk) + suffix)
    lines.append("};")
    return "\n".join(lines)


def main() -> int:
    repo_root = Path(__file__).resolve().parent.parent
    shaders_dir = repo_root / "backends" / "vulkan" / "shaders"
    out_header = repo_root / "backends" / "vulkan" / "generated" / "shaders_spv.h"

    if not GLSLC.is_file():
        print(f"ERROR: glslc not found at {GLSLC}", file=sys.stderr)
        return 1
    if not SPIRV_VAL.is_file():
        print(f"ERROR: spirv-val not found at {SPIRV_VAL}", file=sys.stderr)
        return 1

    comp_files = sorted(shaders_dir.glob("*.comp"))
    if not comp_files:
        print(f"ERROR: No .comp shaders found in {shaders_dir}", file=sys.stderr)
        return 1

    out_header.parent.mkdir(parents=True, exist_ok=True)

    sections: list[str] = [
        "// Auto-generated by tools/compile_shaders.py — DO NOT EDIT.",
        "#pragma once",
        "",
        "#include <cstdint>",
        "",
        "namespace exynova {",
        "namespace gpu {",
        "namespace spv {",
        "",
    ]

    with tempfile.TemporaryDirectory() as tmpdir:
        tmp = Path(tmpdir)
        for comp in comp_files:
            stem = comp.stem
            spv = tmp / f"{stem}.spv"
            words = compile_shader(comp, spv)
            print(
                f"OK  {comp.name:<16} -> kShader_{stem:<14} "
                f"({len(words)} words / {len(words) * 4} bytes, spirv-val OK)"
            )
            sections.append(format_array(stem, words))
            sections.append("")

    sections.extend([
        "}  // namespace spv",
        "}  // namespace gpu",
        "}  // namespace exynova",
        "",
    ])

    out_header.write_text("\n".join(sections), encoding="utf-8")
    print(f"Generated: {out_header}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
